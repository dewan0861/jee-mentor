'use client';

import React, { useState, useEffect, useMemo } from 'react';
import { StorageService } from '@/lib/storage';
import { StudyTask, UserProfile, Subject } from '@/types';
import { JEE_CURRICULUM } from '@/lib/curriculum/data';
import { 
  Calendar, 
  Clock, 
  CheckCircle2, 
  Circle, 
  Plus, 
  Trash2, 
  Sparkles, 
  Target, 
  Award, 
  Flame, 
  Compass, 
  ArrowRight,
  RefreshCw,
  BookOpen,
  Timer
} from 'lucide-react';
import Link from 'next/link';
import confetti from 'canvas-confetti';

export default function PlannerPage() {
  const [profile, setProfile] = useState<UserProfile>(StorageService.getUserProfile());
  const [tasks, setTasks] = useState<StudyTask[]>([]);
  const [newTaskTitle, setNewTaskTitle] = useState('');
  const [newTaskSubject, setNewTaskSubject] = useState<Subject>('physics');
  const [newTaskMinutes, setNewTaskMinutes] = useState(30);
  const [showAddModal, setShowAddModal] = useState(false);
  const [activeTab, setActiveTab] = useState<'today' | 'weekly'>('today');

  const todayStr = useMemo(() => new Date().toISOString().slice(0, 10), []);

  useEffect(() => {
    setProfile(StorageService.getUserProfile());
    setTasks(StorageService.getStudyTasks());
  }, []);

  // Exam countdown calculation
  const countdown = useMemo(() => {
    const targetDate = new Date(`${profile.targetYear || 2027}-01-24T09:00:00`);
    const now = new Date();
    const diffMs = Math.max(0, targetDate.getTime() - now.getTime());
    const totalDays = Math.floor(diffMs / (1000 * 60 * 60 * 24));
    const weeks = Math.floor(totalDays / 7);
    const days = totalDays % 7;
    return { totalDays, weeks, days };
  }, [profile.targetYear]);

  // Today's tasks & completion stats
  const todayTasks = useMemo(() => {
    return tasks.filter((t) => t.dueDate === todayStr);
  }, [tasks, todayStr]);

  const completedTodayCount = todayTasks.filter((t) => t.completed).length;
  const progressPercent = todayTasks.length > 0 ? Math.round((completedTodayCount / todayTasks.length) * 100) : 0;
  const totalEstimatedMinutes = todayTasks.reduce((acc, t) => acc + (t.completed ? t.estimatedMinutes : 0), 0);
  const totalPlannedMinutes = todayTasks.reduce((acc, t) => acc + t.estimatedMinutes, 0);

  const handleToggleTask = (taskId: string) => {
    const updated = StorageService.toggleTaskCompleted(taskId);
    setTasks([...updated]);

    const task = updated.find((t) => t.id === taskId);
    if (task && task.completed) {
      confetti({
        particleCount: 40,
        spread: 50,
        origin: { y: 0.7 },
      });
    }
  };

  const handleAddTask = (e: React.FormEvent) => {
    e.preventDefault();
    if (!newTaskTitle.trim()) return;

    StorageService.addStudyTask({
      title: newTaskTitle.trim(),
      subject: newTaskSubject,
      type: 'custom',
      completed: false,
      dueDate: todayStr,
      estimatedMinutes: newTaskMinutes,
      isAutoGenerated: false,
    });

    setTasks(StorageService.getStudyTasks());
    setNewTaskTitle('');
    setShowAddModal(false);
  };

  const handleDeleteTask = (taskId: string) => {
    const updated = StorageService.deleteStudyTask(taskId);
    setTasks([...updated]);
  };

  const handleRegenerateTasks = () => {
    const generated = StorageService.generateDailyTasks();
    setTasks([...generated]);
  };

  // 7-day rolling schedule
  const weeklyDays = useMemo(() => {
    const days = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'];
    const subjects: Subject[] = ['physics', 'chemistry', 'mathematics', 'physics', 'chemistry', 'mathematics', 'physics'];
    return days.map((day, idx) => {
      const sub = subjects[idx];
      const chapters = JEE_CURRICULUM.filter((c) => c.subject === sub && c.weightage === 'high');
      const chap = chapters[idx % chapters.length];
      return {
        day,
        subject: sub,
        chapterName: chap ? chap.name : 'Core Revision',
        type: idx === 6 ? 'Full Mock Test & Analysis' : 'Concept & High-Yield PYQs',
      };
    });
  }, []);

  return (
    <div className="mx-auto max-w-7xl px-3 sm:px-6 lg:px-8 py-5 sm:py-8">
      {/* Top Countdown Banner */}
      <div className="mb-8 rounded-3xl bg-gradient-to-r from-slate-900 via-indigo-950 to-slate-900 p-5 sm:p-8 text-white shadow-xl relative overflow-hidden border border-slate-800">
        <div className="relative z-10 flex flex-col md:flex-row md:items-center md:justify-between gap-6">
          <div>
            <div className="inline-flex items-center gap-2 rounded-full bg-white/10 px-3.5 py-1 text-xs font-semibold backdrop-blur-md border border-white/10 mb-2">
              <Calendar className="h-3.5 w-3.5 text-amber-400" />
              <span>Target: JEE {profile.targetYear} • {profile.targetRank}</span>
            </div>
            <h1 className="text-2xl sm:text-4xl font-black tracking-tight">
              Personalized Study Planner
            </h1>
            <p className="mt-1.5 text-xs sm:text-sm text-slate-300 max-w-xl">
              Target pace: <strong className="text-indigo-300">{profile.dailyStudyHours} hrs/day</strong>. Calibrated to elevate your performance systematically towards {profile.targetRank}.
            </p>
          </div>

          {/* Countdown Display */}
          <div className="flex items-center gap-3 sm:gap-4 rounded-2xl bg-white/10 p-4 sm:p-5 backdrop-blur-md border border-white/15">
            <div className="text-center">
              <span className="text-2xl sm:text-4xl font-black text-amber-400">{countdown.totalDays}</span>
              <span className="block text-[10px] font-bold uppercase tracking-wider text-slate-300 mt-0.5">Days Left</span>
            </div>
            <div className="h-8 w-px bg-white/20" />
            <div className="text-center">
              <span className="text-2xl sm:text-4xl font-black text-indigo-300">{countdown.weeks}</span>
              <span className="block text-[10px] font-bold uppercase tracking-wider text-slate-300 mt-0.5">Weeks</span>
            </div>
            <div className="h-8 w-px bg-white/20" />
            <div className="text-center">
              <span className="text-2xl sm:text-4xl font-black text-emerald-400">{countdown.days}</span>
              <span className="block text-[10px] font-bold uppercase tracking-wider text-slate-300 mt-0.5">Days</span>
            </div>
          </div>
        </div>
      </div>

      {/* Tabs */}
      <div className="mb-6 flex items-center justify-between">
        <div className="flex rounded-xl bg-slate-200 p-1 dark:bg-slate-800">
          <button
            onClick={() => setActiveTab('today')}
            className={`rounded-lg px-4 py-1.5 text-xs font-bold transition-all ${
              activeTab === 'today'
                ? 'bg-white text-indigo-700 shadow-sm dark:bg-slate-700 dark:text-white'
                : 'text-slate-600 hover:text-slate-900 dark:text-slate-400'
            }`}
          >
            Today's Checklist ({todayTasks.length})
          </button>
          <button
            onClick={() => setActiveTab('weekly')}
            className={`rounded-lg px-4 py-1.5 text-xs font-bold transition-all ${
              activeTab === 'weekly'
                ? 'bg-white text-indigo-700 shadow-sm dark:bg-slate-700 dark:text-white'
                : 'text-slate-600 hover:text-slate-900 dark:text-slate-400'
            }`}
          >
            7-Day Syllabus Blueprint
          </button>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={handleRegenerateTasks}
            className="flex items-center gap-1.5 rounded-xl border border-slate-300 bg-white px-3 py-1.5 text-xs font-bold text-slate-700 hover:bg-slate-50 dark:border-slate-700 dark:bg-slate-800 dark:text-slate-200 transition-colors"
            title="Refresh AI suggested tasks"
          >
            <RefreshCw className="h-3.5 w-3.5 text-indigo-500" />
            <span className="hidden sm:inline">Refresh Tasks</span>
          </button>
          <button
            onClick={() => setShowAddModal(true)}
            className="flex items-center gap-1.5 rounded-xl bg-indigo-600 px-3.5 py-1.5 text-xs font-bold text-white shadow-sm hover:bg-indigo-700 transition-colors"
          >
            <Plus className="h-4 w-4" />
            <span>Add Custom Task</span>
          </button>
        </div>
      </div>

      {/* Tab 1: Today's Dynamic Tasks */}
      {activeTab === 'today' && (
        <div className="space-y-6">
          {/* Progress Card */}
          <div className="rounded-2xl border border-indigo-100 bg-gradient-to-r from-indigo-50/50 via-white to-purple-50/50 p-5 dark:border-slate-800 dark:bg-slate-900">
            <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4">
              <div>
                <span className="text-[11px] font-extrabold uppercase tracking-wider text-indigo-600 dark:text-indigo-400">
                  Daily Execution Rate
                </span>
                <h2 className="text-xl font-black text-slate-900 dark:text-white mt-0.5">
                  {completedTodayCount} of {todayTasks.length} Tasks Mastered ({progressPercent}%)
                </h2>
                <p className="text-xs text-slate-500 mt-1">
                  Completed ~{totalEstimatedMinutes} minutes of focused preparation today.
                </p>
              </div>

              {/* Progress bar */}
              <div className="w-full sm:w-64">
                <div className="flex justify-between text-xs font-bold text-slate-700 dark:text-slate-300 mb-1">
                  <span>Target: {profile.dailyStudyHours} hrs</span>
                  <span className="text-indigo-600 dark:text-indigo-400">{progressPercent}%</span>
                </div>
                <div className="h-3 w-full rounded-full bg-slate-200 dark:bg-slate-800 overflow-hidden">
                  <div
                    className="h-full rounded-full bg-gradient-to-r from-indigo-500 to-emerald-500 transition-all duration-500"
                    style={{ width: `${progressPercent}%` }}
                  />
                </div>
              </div>
            </div>
          </div>

          {/* Task List */}
          <div className="space-y-3">
            {todayTasks.length === 0 ? (
              <div className="rounded-2xl border border-dashed border-slate-300 p-10 text-center dark:border-slate-800">
                <CheckCircle2 className="mx-auto h-10 w-10 text-emerald-500 mb-2" />
                <h3 className="text-sm font-bold text-slate-800 dark:text-slate-200">All tasks completed today!</h3>
                <p className="text-xs text-slate-500 mt-1">Add another task or take a mock exam.</p>
              </div>
            ) : (
              todayTasks.map((task) => (
                <div
                  key={task.id}
                  className={`flex items-center justify-between rounded-2xl border p-4 transition-all ${
                    task.completed
                      ? 'border-emerald-200 bg-emerald-50/40 opacity-80 dark:border-emerald-900/50 dark:bg-emerald-950/20'
                      : 'border-slate-200 bg-white hover:border-indigo-300 dark:border-slate-800 dark:bg-slate-900'
                  }`}
                >
                  <div className="flex items-center gap-3.5 flex-1 min-w-0 pr-3">
                    <button
                      onClick={() => handleToggleTask(task.id)}
                      className="text-slate-400 hover:text-indigo-600 transition-colors shrink-0"
                    >
                      {task.completed ? (
                        <CheckCircle2 className="h-6 w-6 text-emerald-600 fill-emerald-100 dark:fill-emerald-950" />
                      ) : (
                        <Circle className="h-6 w-6" />
                      )}
                    </button>

                    <div className="min-w-0 flex-1">
                      <div className="flex items-center gap-2 mb-1 flex-wrap">
                        {task.subject && (
                          <span className="rounded bg-indigo-50 px-2 py-0.5 text-[10px] font-extrabold uppercase text-indigo-700 dark:bg-indigo-900/40 dark:text-indigo-300">
                            {task.subject}
                          </span>
                        )}
                        <span className="rounded bg-slate-100 px-2 py-0.5 text-[10px] font-bold text-slate-600 dark:bg-slate-800 dark:text-slate-400">
                          {task.type.replace('_', ' ').toUpperCase()}
                        </span>
                        <span className="flex items-center gap-1 text-[11px] font-medium text-slate-400">
                          <Clock className="h-3 w-3" />
                          <span>{task.estimatedMinutes} mins</span>
                        </span>
                      </div>

                      <h4
                        className={`text-sm font-bold leading-snug ${
                          task.completed
                            ? 'line-through text-slate-400 dark:text-slate-500'
                            : 'text-slate-900 dark:text-white'
                        }`}
                      >
                        {task.title}
                      </h4>
                    </div>
                  </div>

                  <div className="flex items-center gap-2 shrink-0">
                    {task.type === 'practice' && (
                      <Link
                        href={`/practice?subject=${task.subject || 'physics'}`}
                        className="rounded-lg bg-indigo-50 px-3 py-1.5 text-xs font-bold text-indigo-600 hover:bg-indigo-100 dark:bg-indigo-900/40 dark:text-indigo-300"
                      >
                        Start
                      </Link>
                    )}
                    {task.type === 'srs_review' && (
                      <Link
                        href="/error-book"
                        className="rounded-lg bg-amber-50 px-3 py-1.5 text-xs font-bold text-amber-700 hover:bg-amber-100 dark:bg-amber-900/40 dark:text-amber-300"
                      >
                        Review
                      </Link>
                    )}
                    {task.type === 'concept' && (
                      <Link
                        href="/curriculum"
                        className="rounded-lg bg-slate-100 px-3 py-1.5 text-xs font-bold text-slate-700 hover:bg-slate-200 dark:bg-slate-800 dark:text-slate-300"
                      >
                        Notes
                      </Link>
                    )}
                    <button
                      onClick={() => handleDeleteTask(task.id)}
                      className="p-1.5 text-slate-400 hover:text-rose-500 transition-colors"
                      title="Delete task"
                    >
                      <Trash2 className="h-4 w-4" />
                    </button>
                  </div>
                </div>
              ))
            )}
          </div>
        </div>
      )}

      {/* Tab 2: 7-Day Rolling Blueprint */}
      {activeTab === 'weekly' && (
        <div className="grid grid-cols-1 gap-4 md:grid-cols-2 lg:grid-cols-3">
          {weeklyDays.map((item, idx) => (
            <div
              key={idx}
              className="rounded-2xl border border-slate-200 bg-white p-5 shadow-sm dark:border-slate-800 dark:bg-slate-900 hover:border-indigo-300 transition-all"
            >
              <div className="flex items-center justify-between mb-3">
                <span className="text-xs font-extrabold uppercase tracking-wider text-slate-400">
                  {item.day}
                </span>
                <span className="rounded bg-indigo-50 px-2 py-0.5 text-[10px] font-extrabold uppercase text-indigo-700 dark:bg-indigo-900/40 dark:text-indigo-300">
                  {item.subject}
                </span>
              </div>
              <h3 className="text-base font-bold text-slate-900 dark:text-white">
                {item.chapterName}
              </h3>
              <p className="text-xs text-slate-500 mt-1">
                {item.type}
              </p>
              <div className="mt-4 pt-3 border-t border-slate-100 dark:border-slate-800 flex items-center justify-between">
                <span className="text-[11px] font-medium text-slate-400">Allocated: 3.5 hrs</span>
                <Link
                  href={`/curriculum`}
                  className="inline-flex items-center gap-1 text-xs font-bold text-indigo-600 hover:text-indigo-700 dark:text-indigo-400"
                >
                  <span>View Chapter</span>
                  <ArrowRight className="h-3 w-3" />
                </Link>
              </div>
            </div>
          ))}
        </div>
      )}

      {/* Add Custom Task Modal */}
      {showAddModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 p-4 backdrop-blur-sm animate-fade-in">
          <div className="relative w-full max-w-md rounded-3xl bg-slate-900 border border-slate-800 p-6 text-white shadow-2xl">
            <h3 className="text-lg font-bold text-white mb-4">Add Custom Study Task</h3>
            <form onSubmit={handleAddTask} className="space-y-4">
              <div>
                <label className="text-xs font-bold uppercase tracking-wider text-slate-400 mb-1.5 block">
                  Task Title
                </label>
                <input
                  type="text"
                  placeholder="e.g. Solve 15 Integral Calculus PYQs"
                  value={newTaskTitle}
                  onChange={(e) => setNewTaskTitle(e.target.value)}
                  className="w-full rounded-xl bg-slate-800 border border-slate-700 px-4 py-2.5 text-sm text-white focus:border-indigo-500 focus:outline-none"
                  required
                />
              </div>

              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="text-xs font-bold uppercase tracking-wider text-slate-400 mb-1.5 block">
                    Subject
                  </label>
                  <select
                    value={newTaskSubject}
                    onChange={(e) => setNewTaskSubject(e.target.value as Subject)}
                    className="w-full rounded-xl bg-slate-800 border border-slate-700 px-3 py-2 text-sm text-white focus:border-indigo-500 focus:outline-none"
                  >
                    <option value="physics">Physics</option>
                    <option value="chemistry">Chemistry</option>
                    <option value="mathematics">Mathematics</option>
                  </select>
                </div>

                <div>
                  <label className="text-xs font-bold uppercase tracking-wider text-slate-400 mb-1.5 block">
                    Estimated Mins
                  </label>
                  <input
                    type="number"
                    min={10}
                    max={180}
                    step={5}
                    value={newTaskMinutes}
                    onChange={(e) => setNewTaskMinutes(parseInt(e.target.value, 10))}
                    className="w-full rounded-xl bg-slate-800 border border-slate-700 px-3 py-2 text-sm text-white focus:border-indigo-500 focus:outline-none"
                  />
                </div>
              </div>

              <div className="flex justify-end gap-2 pt-2">
                <button
                  type="button"
                  onClick={() => setShowAddModal(false)}
                  className="rounded-xl px-4 py-2 text-xs font-bold text-slate-400 hover:text-white"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  className="rounded-xl bg-indigo-600 px-5 py-2 text-xs font-bold text-white hover:bg-indigo-500"
                >
                  Save Task
                </button>
              </div>
            </form>
          </div>
        </div>
      )}
    </div>
  );
}
